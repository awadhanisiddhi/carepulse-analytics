-- 15. Rank doctors within their department
WITH doctor_admissions AS (
    SELECT
        doc.doctor_id,
        doc.doctor_name,
        d.department_name,
        COUNT(a.admission_id) AS total_admissions
    FROM doctors doc
    JOIN departments d
        ON doc.department_id = d.department_id
    LEFT JOIN admissions a
        ON doc.doctor_id = a.doctor_id
    GROUP BY
        doc.doctor_id,
        doc.doctor_name,
        d.department_name
)

SELECT
    doctor_name,
    department_name,
    total_admissions,
    RANK() OVER (
        PARTITION BY department_name
        ORDER BY total_admissions DESC
    ) AS department_rank
FROM doctor_admissions
ORDER BY department_name, department_rank;
