CREATE DATABASE carepulse;
use carepulse;

CREATE TABLE departments (
    department_id VARCHAR(10) PRIMARY KEY,
    department_name VARCHAR(100),
    bed_capacity INT
);

CREATE TABLE doctors (
    doctor_id VARCHAR(10) PRIMARY KEY,
    doctor_name VARCHAR(100),
    department_id VARCHAR(10),
    specialization VARCHAR(100),
    experience_years INT,
    FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE TABLE patients (
    patient_id VARCHAR(15) PRIMARY KEY,
    patient_name VARCHAR(100),
    age INT,
    gender VARCHAR(20),
    city VARCHAR(100),
    blood_group VARCHAR(5),
    phone VARCHAR(20),
    insurance_type VARCHAR(50)
);

CREATE TABLE admissions (
    admission_id VARCHAR(15) PRIMARY KEY,
    patient_id VARCHAR(15),
    doctor_id VARCHAR(10),
    department_id VARCHAR(10),
    admission_date DATE,
    discharge_date DATE,
    admission_type VARCHAR(30),
    diagnosis VARCHAR(100),
    waiting_time_minutes INT,
    emergency_priority VARCHAR(30),
    length_of_stay INT,
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    FOREIGN KEY (doctor_id) REFERENCES doctors(doctor_id),
    FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE TABLE billing (
    bill_id VARCHAR(15) PRIMARY KEY,
    admission_id VARCHAR(15),
    treatment_cost DECIMAL(12,2),
    medicine_cost DECIMAL(12,2),
    room_charges DECIMAL(12,2),
    total_bill DECIMAL(12,2),
    insurance_covered DECIMAL(12,2),
    payment_status VARCHAR(30),
    FOREIGN KEY (admission_id) REFERENCES admissions(admission_id)
);


